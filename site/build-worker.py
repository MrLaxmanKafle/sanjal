"""Builds site/worker.js from site/public/index.html and
site/functions/api/waitlist.js. Run from the repo root: python3 site/build-worker.py"""
import json

html = open('site/public/index.html').read()
fn = open('site/functions/api/waitlist.js').read().replace(
    'export async function onRequestPost({ request, env })',
    'async function saveEmail(request, env)',
)

worker = '''// Single Cloudflare Worker for sanjal.com. Generated by site/build-worker.py
// from site/public/index.html and site/functions/api/waitlist.js; edit those.
const PAGE = %s;

%s
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.hostname === 'www.sanjal.com') {
      url.hostname = 'sanjal.com';
      return Response.redirect(url.toString(), 301);
    }
    if (url.pathname === '/api/waitlist') {
      if (request.method !== 'POST') {
        return json({ ok: false, error: 'method_not_allowed' }, 405);
      }
      return saveEmail(request, env);
    }
    if (url.pathname === '/' || url.pathname === '/index.html') {
      return new Response(PAGE, {
        headers: {
          'content-type': 'text/html; charset=utf-8',
          'cache-control': 'public, max-age=300',
          'x-content-type-options': 'nosniff',
        },
      });
    }
    return new Response('Not found', { status: 404 });
  },
};
''' % (json.dumps(html), fn)

open('site/worker.js', 'w').write(worker)
